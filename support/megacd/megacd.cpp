#define SAVE_IO_INDEX 5 // fake download to trigger save loading

#define MCD_GET_CMD        0
#define MCD_GET_SEND_DATA  1

static int need_reset=0;
static uint8_t has_command = 0;

void mcd_poll()
{
	static uint32_t poll_timer = 0;
	static uint8_t last_req = 255;
	static uint8_t adj = 0;

	if (!poll_timer || CheckTimer(poll_timer))
	{
		if (!cdd.isData && cdd.status == CD_STAT_PLAY && cdd.latency == 0) {
			// Send audio sectors faster so buffer stays filled
			poll_timer = GetTimer(10);
			adj = 0;
		} else {
			poll_timer = GetTimer(13 + (!adj ? 1 : 0));
			if (++adj >= 3) adj = 0;
		}

		if (has_command) {
			spi_uio_cmd_cont(UIO_CD_SET);
			uint64_t s = cdd.GetStatus(0);
			spi_w((s >> 0) & 0xFFFF);
			spi_w((s >> 16) & 0xFFFF);
			spi_w(((s >> 32) & 0x00FF) | (cdd.isData ? 0x01 << 8 : 0x00 << 8));
			DisableIO();

			has_command = 0;

			//printf("\x1b[32mMCD: Send status, status = %04X%04X%04X, frame = %u\n\x1b[0m", (uint16_t)((s >> 32) & 0x00FF), (uint16_t)((s >> 16) & 0xFFFF), (uint16_t)((s >> 0) & 0xFFFF), frame);
		}

		cdd.Update();
	}


	uint8_t req = spi_uio_cmd_cont(UIO_CD_GET);
	if (req != last_req)
	{
		last_req = req;

		spi_w(MCD_GET_CMD);

		uint16_t data_in[4];
		data_in[0] = spi_w(0);
		data_in[1] = spi_w(0);
		data_in[2] = spi_w(0);
		DisableIO();

		if (need_reset || data_in[0] == 0xFF) {
			printf("MCD: request to reset\n");
			need_reset = 0;
			cdd.Reset();
		}

		uint64_t c = *((uint64_t*)(data_in));
		cdd.SetCommand(c, 0);
		cdd.CommandExec();
		has_command = 1;


		//printf("\x1b[32mMCD: Get command, command = %04X%04X%04X, has_command = %u\n\x1b[0m", data_in[2], data_in[1], data_in[0], has_command);
	}
	else
		DisableIO();
}

static char buf[1024];
static void mcd_mount_save(const char *filename)
{
	user_io_set_index(SAVE_IO_INDEX);
	user_io_set_download(1);
	if (strlen(filename))
	{
		FileGenerateSavePath(filename, buf);
		user_io_file_mount(buf, 0, 1);
	}
	else
	{
		user_io_file_mount("");
	}
	user_io_set_download(0);
}

static int mcd_load_rom(const char *basename, const char *name, int sub_index)
{
	strcpy(buf, basename);
	char *p = strrchr(buf, '/');
	if (p)
	{
		p++;
		strcpy(p, name);
		if (user_io_file_tx(buf, sub_index << 6)) return 1;
	}

	return 0;
}

void mcd_set_image(int num, const char *filename)
{
	static char last_dir[1024] = {};

	(void)num;

	cdd.Unload();
	cdd.status = CD_STAT_OPEN;

	// "Same game" decides whether the disc is hot-swapped (drive only, core keeps running) or the
	// machine is restarted with that game's BIOS, save and cheats.  The test is a directory-prefix
	// match, which is right for a multi-disc game in its own folder but wrong for the far more
	// common flat folder of unrelated games: there every title matches every other, so inserting a
	// different game hot-swapped the disc into the previous game's BIOS and save file and, to the
	// user, "nothing happened".
	//
	// The MegaCD core offers "Disc Insert: Reset | Keep Running" for exactly this choice, so ask
	// it.  Default (bit 36 clear) restarts on every disc change, which is what a flat library
	// wants; set it for a multi-disc game and the directory match applies as before.  Cores that
	// do not define bit 36 read 0 and get the restart behaviour.
	int keep_running = is_megacd() ? (int)user_io_status_get("[36]") : 0;
	int same_game = keep_running && *filename && *last_dir && !strncmp(last_dir, filename, strlen(last_dir));
	printf("MCD: disc change - keep_running=%d same_game=%d (%s)\n", keep_running, same_game,
	       same_game ? "swap the disc, core keeps running" : "new game: swap save/cheats; disc inserted, console keeps running");
	strcpy(last_dir, filename);
	char *p = strrchr(last_dir, '/');
	if (p) *p = 0;

	// A disc insert is a tray-close on a RUNNING console and must NOT reset the machine.  On a real
	// Mega CD you open the tray, swap the disc and close it; the drive reports tray-open then
	// disc-present and the software reacts - the BIOS boots the new disc, a running game halts
	// until you press Reset.  The console's BIOS ROM is not part of the disc (Main loads
	// <home>/boot.rom at core start), so it is NOT reloaded here: in the core a BIOS download is a
	// full cold reset (bios_download -> loading -> md_reset), which was exactly the unwanted
	// "insert a disc at the BIOS => the machine resets".  The only downloads left on this path are a
	// game's OWN cd_bios.rom / cart.rom - a genuine BIOS/cartridge swap that cannot happen under a
	// running CPU, so those still reset, but only when such a file exists (user_io_file_tx opens the
	// file before it touches the download strobe).  Swapping the per-game save (mcd_mount_save is an
	// SD-image mount on index 5, not a ROM index) and the cheats is HPS-side bookkeeping and does
	// not reset the core.  "Reset & Eject CD" (R[0]) still resets: menu.cpp pulses status[0] itself.
	if (!same_game) mcd_mount_save("");   // flush/close the previous game's save before swapping

	if (*filename)
	{
		if (cdd.Load(filename) > 0)
		{
			cdd.status = cdd.loaded ? CD_STAT_STOP : CD_STAT_NO_DISC;   // tray closed, disc present
			cdd.latency = 10;
			cdd.SendData = mcd_send_data;
			cdd.CanSendData = mcd_can_send_data;

			if (!same_game)
			{
				int own_bios = mcd_load_rom(filename, "cd_bios.rom", 0);  // only if the game ships one (resets)
				mcd_load_rom(filename, "cart.rom", 1);                    // only if the game ships one (resets)
				mcd_mount_save(filename);
				cheats_init(filename, 0);

				// Nothing to run?  Warn if <home>/boot.rom is missing and the game brought no BIOS.
				if (!own_bios)
				{
					sprintf(buf, "%s/boot.rom", HomeDir());
					if (!FileExists(buf)) Info("CD BIOS not found!", 4000);
				}
			}
		}
		else
		{
			cdd.status = CD_STAT_NO_DISC;
		}
	}
}

void mcd_reset() {
	need_reset = 1;
}

// "Eject Disc" (OSD R[38]): open the tray WITHOUT resetting either 68000 or reloading the BIOS.
// The running BIOS sees the drive report CD_STAT_OPEN on the next 75 Hz poll and behaves as if the
// disc were physically removed (as on hardware). Re-inserting via the OSD file browser calls
// mcd_set_image() again. This is the eject half of "Reset & Eject CD" (R[0]) split out on its own.
void mcd_eject() {
	printf("MCD: eject - tray open, core left running\n");
	cdd.Unload();
	cdd.status = CD_STAT_OPEN;
}

int mcd_send_data(uint8_t* buf, int len, uint8_t index) {
	// set index byte
	user_io_set_index(index);

	user_io_set_download(1);
	user_io_file_tx_data(buf, len);
	user_io_set_download(0);
	return 1;
}

